-- ============================================================================
-- Tabla principal: gth_postulante_formulario (1:1 con gth_candidato)
-- ============================================================================
CREATE TABLE IF NOT EXISTS gth_postulante_formulario (
    gth_postulante_formulario_id        integer GENERATED BY DEFAULT AS IDENTITY,
    gth_candidato_id                    integer NOT NULL,
    token                               text    NOT NULL,
    gth_postulante_formulario_estado_id integer NOT NULL,
    correo_envio                        text    NOT NULL,

    enviado_date_time    timestamptz NULL,
    enviado_user_id      integer     NULL,
    completado_date_time timestamptz NULL,
    revisado_user_id     integer     NULL,
    revisado_nombre      text        NULL,
    revisado_date_time   timestamptz NULL,
    motivo_rechazo       text        NULL,

    -- Página 1 · Datos personales
    nombres_completos          text    NULL,
    fecha_nacimiento           date    NULL,
    gth_estado_civil_id        integer NULL,
    gth_tipo_documento_id      integer NULL,
    numero_documento           text    NULL,
    gth_distrito_id            integer NULL,
    correo_electronico         text    NULL,
    numero_celular             text    NULL,
    convocatoria_gth_puesto_id integer NULL,
    pretensiones_salariales    text    NULL,
    gth_disponibilidad_id      integer NULL,
    linkedin                   text    NULL,
    portafolio_link            text    NULL,

    -- Página 2 · Estudios realizados
    profesion             text    NULL,
    gth_universidad_id    integer NULL,
    gth_grado_academico_id integer NULL,
    numero_colegiatura    text    NULL,

    -- Página 3 · Experiencia laboral (más reciente)
    empresa                              text    NULL,
    area_trabajo                         text    NULL,
    cargo                                text    NULL,
    fecha_inicio                         date    NULL,
    fecha_termino                        date    NULL,
    gth_motivo_cese_id                   integer NULL,
    funciones_principales                text    NULL,
    logros                               text    NULL,
    ingreso_bruto_mensual                text    NULL,
    personas_a_cargo                     integer NULL,
    jefe_inmediato                       text    NULL,
    autoriza_verificacion_referencias    boolean NULL,

    -- Página 4 · Consentimiento y veracidad
    declaracion_veracidad   boolean NULL,
    confirmacion_documentos boolean NULL,

    created_date_time timestamptz NOT NULL DEFAULT now(),
    created_user_id   integer     NULL,
    updated_date_time timestamptz NULL,
    updated_user_id   integer     NULL,
    active            boolean     NOT NULL DEFAULT true,
    state             boolean     NOT NULL DEFAULT true,

    CONSTRAINT pk_gth_postulante_formulario PRIMARY KEY (gth_postulante_formulario_id),
    CONSTRAINT fk_gpf_candidato
        FOREIGN KEY (gth_candidato_id) REFERENCES gth_candidato(gth_candidato_id),
    CONSTRAINT fk_gpf_estado
        FOREIGN KEY (gth_postulante_formulario_estado_id) REFERENCES gth_postulante_formulario_estado(gth_postulante_formulario_estado_id),
    CONSTRAINT fk_gpf_estado_civil
        FOREIGN KEY (gth_estado_civil_id) REFERENCES gth_estado_civil(gth_estado_civil_id),
    CONSTRAINT fk_gpf_tipo_documento
        FOREIGN KEY (gth_tipo_documento_id) REFERENCES gth_tipo_documento(gth_tipo_documento_id),
    CONSTRAINT fk_gpf_distrito
        FOREIGN KEY (gth_distrito_id) REFERENCES gth_distrito(gth_distrito_id),
    CONSTRAINT fk_gpf_convocatoria_puesto
        FOREIGN KEY (convocatoria_gth_puesto_id) REFERENCES gth_puesto(gth_puesto_id),
    CONSTRAINT fk_gpf_disponibilidad
        FOREIGN KEY (gth_disponibilidad_id) REFERENCES gth_disponibilidad(gth_disponibilidad_id),
    CONSTRAINT fk_gpf_universidad
        FOREIGN KEY (gth_universidad_id) REFERENCES gth_universidad(gth_universidad_id),
    CONSTRAINT fk_gpf_grado_academico
        FOREIGN KEY (gth_grado_academico_id) REFERENCES gth_grado_academico(gth_grado_academico_id),
    CONSTRAINT fk_gpf_motivo_cese
        FOREIGN KEY (gth_motivo_cese_id) REFERENCES gth_motivo_cese(gth_motivo_cese_id)
);

-- Un solo formulario vivo por candidato (1:1) y token único entre los vigentes.
