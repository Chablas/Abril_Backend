-- 20260930_PropietarioDocumentoFolder_DevDemo.sql en dev y demo. Sin fila vigente, subir un
-- documento avisa que falta.

-- Verificación
SELECT (SELECT string_agg(nombre, ', ' ORDER BY orden)
        FROM propietario_documento_tipo WHERE state)              AS tipos,
       to_regclass('public.propietario_documento') IS NOT NULL    AS tabla_documentos,
       (SELECT link_url FROM propietario_documento_folder
        WHERE state AND active)                                   AS carpeta;
