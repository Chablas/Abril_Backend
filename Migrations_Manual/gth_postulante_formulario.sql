-- ============================================================================
-- Gestión GTH · Reclutamiento — Formulario de información del postulante
--
-- Traslada al sistema el formulario que hoy vive en Microsoft Forms
-- ("FORMULARIO POSTULANTE - ABRIL GRUPO INMOBILIARIO"). GTH envía el enlace al
-- correo de cada candidato APROBADO; el postulante lo llena desde una página
-- pública (acceso por token, sin login) y GTH lo revisa (aprueba/rechaza).
--
--   Catálogos (datos predefinidos normalizados en su propia tabla):
--     • gth_postulante_formulario_estado : ENVIADO / COMPLETADO / APROBADO / RECHAZADO
--     • gth_estado_civil                 : Soltero(a) … Conviviente
--     • gth_tipo_documento               : DNI / CE
--     • gth_grado_academico              : Egresado … No culminado o trunco
--     • gth_disponibilidad               : Inmediata … Más de 15 días
--     • gth_motivo_cese                  : Renuncia personal … Otras
--     • gth_universidad                  : universidades del país + Otras
--     • gth_distrito                     : distritos de Lima y Callao (provincia)
--   Tabla principal:
--     • gth_postulante_formulario        : 1:1 con gth_candidato; token de acceso
--                                          público + los campos de las 4 páginas.
--       La "convocatoria de interés" reutiliza el catálogo gth_puesto.
--
-- Idempotente: se puede correr múltiples veces sin duplicar ni romper nada.
-- ============================================================================

